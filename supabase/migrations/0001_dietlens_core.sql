-- DietLens Supabase schema. Apply with `supabase db push` after linking a project.
-- Backend writes use a secret key or an authenticated server session; browser code never uses it.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id text primary key,
  version integer not null default 1,
  payload jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.profile_versions (
  user_id text not null,
  version integer not null,
  payload jsonb not null,
  task_id text,
  operation_key text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, version)
);
create table if not exists public.profile_drafts (
  task_id text primary key,
  user_id text not null,
  expected_version integer not null,
  payload jsonb not null,
  changes jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.consents (
  user_id text not null,
  scope text not null check (scope in ('history','image_transfer','review_history','reminders')),
  profile_version integer not null,
  granted boolean not null,
  source text not null,
  task_id text not null,
  operation_key text not null,
  created_at timestamptz not null default now(),
  primary key (user_id, scope, profile_version)
);
create table if not exists public.tasks (
  task_id text primary key,
  user_id text not null,
  task_type text not null default 'micro_action',
  state text not null,
  version integer not null default 1,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.food_observations (
  observation_id uuid primary key default gen_random_uuid(),
  user_id text not null,
  task_id text,
  source text not null,
  source_id text,
  status text not null check (status in ('safe','blocked','needs_confirmation')),
  payload jsonb not null,
  retrieved_at timestamptz not null,
  created_at timestamptz not null default now()
);
create table if not exists public.actions (
  action_id text primary key,
  user_id text not null,
  task_id text,
  payload jsonb not null,
  created_at timestamptz not null default now()
);
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  task_id text not null,
  user_id text not null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  operation_key text,
  created_at timestamptz not null default now()
);
create table if not exists public.operations (
  operation_key text primary key,
  user_id text not null,
  request_hash text not null,
  payload jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists tasks_user_idx on public.tasks(user_id, updated_at desc);
create index if not exists events_task_idx on public.events(task_id, created_at);
create index if not exists food_observations_user_idx on public.food_observations(user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.profile_versions enable row level security;
alter table public.profile_drafts enable row level security;
alter table public.consents enable row level security;
alter table public.tasks enable row level security;
alter table public.food_observations enable row level security;
alter table public.actions enable row level security;
alter table public.events enable row level security;
alter table public.operations enable row level security;

-- Browser access is restricted to an authenticated user's own user_id.
-- The Python server uses a secret key and performs the same user ownership checks.
do $$
declare t text;
begin
  foreach t in array array['profiles','profile_versions','profile_drafts','consents','tasks','food_observations','actions','events','operations'] loop
    execute format('drop policy if exists %I on public.%I', t || '_owner', t);
    execute format('create policy %I on public.%I for all to authenticated using (auth.uid()::text = user_id) with check (auth.uid()::text = user_id)', t || '_owner', t);
  end loop;
end $$;

create or replace function public.commit_profile_draft(
  p_user_id text, p_task_id text, p_operation_key text, p_expected_version integer
) returns jsonb language plpgsql security definer set search_path = public as $$
declare d record; current_version integer; next_version integer; result jsonb;
begin
  if current_user not in ('postgres', 'service_role') and (auth.uid() is null or auth.uid()::text <> p_user_id) then
    raise exception 'profile_owner_required';
  end if;
  select payload into result from public.operations where operation_key = p_operation_key and user_id = p_user_id;
  if found then return result; end if;
  select * into d from public.profile_drafts where task_id = p_task_id and user_id = p_user_id for update;
  if not found then raise exception 'profile_draft_not_found'; end if;
  select version into current_version from public.profiles where user_id = p_user_id for update;
  current_version := coalesce(current_version, 0);
  if current_version <> p_expected_version or d.expected_version <> p_expected_version then raise exception 'version_conflict'; end if;
  select jsonb_build_object('profile', d.payload, 'profile_version', current_version + 1) into result;
  insert into public.profile_versions(user_id, version, payload, task_id, operation_key)
    values (p_user_id, current_version + 1, d.payload, p_task_id, p_operation_key);
  insert into public.profiles(user_id, version, payload)
    values (p_user_id, current_version + 1, d.payload)
    on conflict (user_id) do update set version = excluded.version, payload = excluded.payload, updated_at = now();
  insert into public.operations(operation_key, user_id, request_hash, payload)
    values (p_operation_key, p_user_id, md5(p_task_id || ':' || p_expected_version::text), result)
    on conflict (operation_key) do nothing;
  update public.tasks set state = 'done', version = version + 1, updated_at = now() where task_id = p_task_id and user_id = p_user_id;
  insert into public.events(task_id, user_id, event_type, payload, operation_key)
    values (p_task_id, p_user_id, 'profile.confirmed', result, p_operation_key);
  return result;
end $$;
revoke all on function public.commit_profile_draft(text,text,text,integer) from public;
grant execute on function public.commit_profile_draft(text,text,text,integer) to authenticated, service_role;
