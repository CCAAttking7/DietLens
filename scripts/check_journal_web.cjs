// Actual local demo API, isolated synthetic account. No model calls or real user writes.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 const base=process.env.DIETLENS_PREVIEW_URL||'http://127.0.0.1:5174';
 const user='synthetic-journal-'+Date.now();
 page.on('pageerror',e=>errors.push(e.message));
 const post=async(path,data)=>{const result=await page.request.post(base+path,{data});if(!result.ok())throw Error(`${path}: ${result.status()}`);return result.json()};
 const profile=await post('/api/profile/preview',{user_id:user,changes:{goal:'合成记录流程测试'},expected_version:0,consents:{review_history:false}});
 await post('/api/profile/confirm',{user_id:user,task_id:profile.task_id,operation_key:'synthetic:'+profile.task_id,expected_version:profile.expected_version});
 await page.route('**/api/**',async r=>{const req=r.request();await r.continue({url:req.url().replaceAll('web-demo-user',user),...(req.postData()?{postData:req.postData().replaceAll('web-demo-user',user)}:{})})});
 await page.goto(base);await page.getByRole('textbox',{name:'描述这一餐'}).waitFor();
 await page.locator('.side-nav button').filter({hasText:'饮食回顾'}).click();
 await page.getByRole('button',{name:'查看并开启历史回顾'}).waitFor();
 await page.getByRole('button',{name:'先记下一餐',exact:true}).click();
 await page.getByRole('button',{name:'记录已吃的一餐',exact:true}).click();
 await page.getByRole('textbox',{name:'实际餐食名称',exact:true}).fill('合成记录番茄面');
 await page.keyboard.press('Escape');
 await page.locator('.side-nav button').filter({hasText:'饮食回顾'}).click();
 if(await page.getByRole('textbox',{name:'实际餐食名称',exact:true}).inputValue()!=='合成记录番茄面')throw Error('journal draft lost on return');
 await page.getByRole('button',{name:'预览这条记录',exact:true}).click();
 await page.getByRole('region',{name:'实际餐食预览'}).filter({hasText:'份量未知'}).waitFor();
 let failConfirm=true;
 await page.route('**/api/meal-records/confirm',async r=>{if(failConfirm){failConfirm=false;await r.fulfill({status:503,json:{}})}else await r.fallback()});
 await page.getByRole('button',{name:'确认保存这一餐',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'服务暂时不可用'}).waitFor();
 await page.getByRole('button',{name:'确认保存这一餐',exact:true}).click();
 await page.getByRole('status').filter({hasText:'这一餐已保存'}).waitFor();
 if(await page.locator('.journal-list article').count()!==1)throw Error('retry produced duplicate or missing record');
 const records=await (await page.request.get(`${base}/api/meal-records?user_id=${user}`)).json();
 if(records.length!==1||records[0].quantity!==null||records[0].unit!==null)throw Error('unknown portion not persisted as null');
 await page.getByRole('button',{name:'修改餐食合成记录番茄面',exact:true}).click();
 await page.getByRole('textbox',{name:'实际餐食名称',exact:true}).fill('合成修改鸡蛋面');
 await page.getByRole('textbox',{name:'实际餐食份量',exact:true}).fill('1');
 await page.getByRole('button',{name:'预览这条记录',exact:true}).click();
 await page.getByRole('button',{name:'确认修改记录',exact:true}).waitFor();
 await page.getByRole('textbox',{name:'实际餐食份量',exact:true}).fill('2');
 if(await page.getByRole('button',{name:'确认修改记录',exact:true}).count())throw Error('edited journal has stale preview');
 await page.getByRole('button',{name:'预览这条记录',exact:true}).click();
 await page.getByRole('button',{name:'确认修改记录',exact:true}).click();
 await page.locator('.journal-list article').filter({hasText:'合成修改鸡蛋面'}).filter({hasText:'2份'}).waitFor();
 await page.getByRole('button',{name:'这段时间',exact:true}).click();
 await page.getByRole('button',{name:'查看并开启历史回顾'}).click();
 await page.getByRole('heading',{name:'确认这份饮食档案'}).waitFor();
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'确认并进入',exact:true}).click();
 await page.locator('.onboarding-drawer').waitFor({state:'hidden'});
 await page.locator('.review-grid').waitFor();
 if(await page.locator('.metric').filter({hasText:'实际记录'}).locator('strong').innerText()!=='1')throw Error('meal not counted after consent');
 await page.getByRole('button',{name:'用餐记录',exact:true}).click();
 await page.getByRole('button',{name:'删除餐食合成修改鸡蛋面',exact:true}).click();
 await page.getByRole('button',{name:'保留记录',exact:true}).click();
 if(await page.locator('.journal-list article').count()!==1)throw Error('cancel deletion removed record');
 let failDelete=true;
 await page.route('**/api/meal-records/*?expected_version=*',async r=>{if(failDelete){failDelete=false;await r.fulfill({status:503,json:{}})}else await r.fallback()});
 await page.getByRole('button',{name:'删除餐食合成修改鸡蛋面',exact:true}).click();
 await page.getByRole('button',{name:'确认删除这条记录',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'服务暂时不可用'}).waitFor();
 await page.getByRole('button',{name:'确认删除这条记录',exact:true}).click();
 await page.getByRole('heading',{name:'还没有实际用餐记录'}).waitFor();
 await page.getByRole('button',{name:'这段时间',exact:true}).click();
 await page.locator('.review-grid').waitFor();
 if(await page.locator('.metric').filter({hasText:'实际记录'}).locator('strong').innerText()!=='0')throw Error('deleted meal remained in review');
 await post('/api/delete',{user_id:user,confirmed:true});
 if(errors.length)throw Error(errors.join(';'));
 console.log(JSON.stringify({recordWithoutReviewConsent:'passed',draftRecovery:'passed',unknownPortion:'passed',confirmationFailureRetry:'passed',editAndInvalidatePreview:'passed',consentReturnToReview:'passed',reviewCountsSavedAndDeletedRecords:'passed',deleteCancelAndRetry:'passed',pageErrors:errors}));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
